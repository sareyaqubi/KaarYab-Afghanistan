let _n = 0;
function job(partial: Omit<Job, "id" | "views" | "applications" | "saves"> & Partial<Pick<Job, "views" | "applications" | "saves">>): Job {
  _n += 1;
  return {
    id: `j${_n}`,
    views: Math.floor(Math.random() * 800) + 60,
    applications: Math.floor(Math.random() * 40) + 2,
    saves: Math.floor(Math.random() * 30) + 1,
    ...partial,
  };
}

const daysFromNow = (days: number) => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  return d.toISOString();
};
const daysAgo = (days: number) => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  return d.toISOString();
};

